        other_windows = [
            (datetime(2025, 3, 1), datetime(2025, 6, 30, 23, 59, 59)),
            (datetime(2025, 8, 26), datetime(2026, 6, 4, 23, 59, 59)),
            (datetime(2026, 8, 28), datetime(2026, 9, 8, 23, 59, 59)),
        ]

        created_ids = []
        for i, (lang, period) in enumerate(zip(langs, periods)):
            pair = PAIRS[i % len(PAIRS)]
            if lang == "kk":
                q = rng.choice(KK_PREFIX) + pair["kk_q"].rstrip("?") + rng.choice(KK_SUFFIX)
                a = pair["kk_a"]
                q_ru = pair["ru_q"]
            else:
                q = rng.choice(RU_PREFIX) + pair["ru_q"].rstrip("?") + rng.choice(RU_SUFFIX)
                a = pair["ru_a"]
                q_ru = pair["ru_q"]
            q = " ".join(q.split())
            if not q.endswith("?"):
                q += "?"

            if period == "a":
                created = random_dt(rng, start_a, end_a)
            elif period == "b":
                created = random_dt(rng, start_b, end_b)
            else:
                w0, w1 = rng.choice(other_windows)
                created = random_dt(rng, w0, w1)

            obj = QuestionLog.objects.create(
                user=rng.choice(users),
                question=q,
                question_ru=q_ru,
                answer=a,
                language=lang,
                source=QuestionLog.SOURCE_RAG,
                is_unanswered=False,
            )
            created_ids.append((obj.pk, created))

        for pk, created in created_ids:
            QuestionLog.objects.filter(pk=pk).update(created_at=created)

        self.stdout.write(
            self.style.SUCCESS(
                f"Создано {TOTAL} вопросов: kk={KK_COUNT}, ru={RU_COUNT}; "
                f"2025-07-01..08-25={RANGE_A}, 2026-06-05..08-27={RANGE_B}, прочее={RANGE_C}."
            )
        )
